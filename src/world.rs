    fn get_tile(&self, x_cord: usize, y_cord: usize) -> u8 {
        self.tiles[y_cord * self.width + x_cord]
    }
    pub fn is_wall(&self, x_cord: usize, y_cord: usize) -> bool {
        let tile = self.get_tile(x_cord, y_cord);
        let wall = match tile {
            1 => true,
            2 => {
                if let Some(door) = self.doors.iter().find(|d| d.x == x_cord && d.y == y_cord) {
                    return door.open_amount < 1.0;
                }
                false
            }
            _ => false,
        };
        wall
    }
    pub fn update_doors(&mut self, delta_time: f32) {
        for door in self.doors.iter_mut() {
            if door.is_open && door.open_amount < 1.0 {
                door.open_amount += delta_time * 1.5;
                if door.open_amount > 1.0 {
                    door.open_amount = 1.0
                }
            }
        }
    }
    pub fn interact(&mut self, player_x: f32, player_y: f32, player_angle: f32) {
        let reach = 1.5;
        let target_x = (player_x + reach * player_angle.cos()) as usize;
        let target_y = (player_y + reach * player_angle.sin()) as usize;

        for door in self.doors.iter_mut() {
            if door.x == target_x && door.y == target_y {
                door.is_open = true;
            }
        }
    }
